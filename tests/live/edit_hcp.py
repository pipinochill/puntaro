"""Edit handicap for guests and friends without the app: from New round's player list and from their profile.
Puntaro friends (and you) can't be changed here."""
import asyncio, re, sys
from playwright.async_api import async_playwright
sys.path.insert(0, sys.argv[3]); import rules, fakecloud as fc
URL, OUT = sys.argv[1], sys.argv[2]; res = []
def check(n, ok, d=''): ok = bool(ok); res.append(ok); print(('PASS ' if ok else 'FAIL ') + n + (f'  [{d}]' if d and not ok else ''))
cloud = fc.Cloud(rules)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); cloud.seed('u_a', fc.profile('Pierre'))
        A = await cloud.phone(b, 'u_a'); await fc.open_app(A, URL)
        await A.get_by_role('button', name='Start a round').click(); await A.wait_for_timeout(300)
        await A.get_by_role('button', name='+ Guest').click(); await A.wait_for_timeout(300)
        await A.get_by_label('Name', exact=True).fill('Tom'); await A.get_by_label('Last name').fill('Jones')
        await A.get_by_label('Handicap index').fill('18.0')
        await A.get_by_role('button', name='Add to round').click(); await A.wait_for_timeout(300)
        edit = A.get_by_role('button', name="Edit Tom's handicap")
        check('A guest in the round has Edit HCP', await edit.count() == 1)
        n_edit = await A.get_by_role('button', name=re.compile(r"^Edit .*'s handicap$")).count()
        n_others = await A.get_by_role('button', name=re.compile(r"^Remove ")).count()  # every player but you
        check('Every other player you score for has it, but not you (yours is on Me)', n_edit == n_others and n_edit >= 1, f'{n_edit} vs {n_others}')
        await edit.click(); await A.wait_for_timeout(300)
        sheet = A.get_by_role('dialog', name="Tom's handicap")
        check('It opens on their current handicap', await sheet.count() == 1 and await sheet.get_by_label('Handicap index').input_value() == '18.0')
        await sheet.get_by_label('Handicap index').fill('99')
        check('A handicap out of range can\'t be saved', await sheet.get_by_role('button', name='Save handicap').is_disabled() and await sheet.get_by_role('alert').count() == 1)
        await sheet.get_by_label('Handicap index').fill('12.4'); await sheet.get_by_role('button', name='Save handicap').click(); await A.wait_for_timeout(300)
        check('Saving updates the player list', await A.get_by_text('HCP 12.4 · guest').count() == 1 and await sheet.count() == 0)
        await edit.click(); await A.wait_for_timeout(300)
        await sheet.get_by_role('button', name='No handicap', exact=True).click(); await sheet.get_by_role('button', name='90 to 99', exact=True).click()
        await sheet.get_by_role('button', name='Save handicap').click(); await A.wait_for_timeout(300)
        check('...and can switch them to an estimate, marked EST', await A.get_by_text('HCP 20.0 EST · guest').count() == 1)
        await edit.click(); await A.wait_for_timeout(300)
        check('An estimate reopens on their usual score', await sheet.get_by_role('button', name='90 to 99', exact=True).get_attribute('class') == 'chip on')
        await sheet.get_by_role('button', name='Close').click(); await A.wait_for_timeout(200)
        await A.screenshot(path=f'{OUT}/edit_hcp_setup.png')
        await fc.flushed(A)
        await fc.open_app(A, URL); await A.wait_for_timeout(500)
        await A.get_by_role('button', name='Start a round').click(); await A.wait_for_timeout(300)
        if await A.get_by_role('button', name='+ Friend').count() == 0: await A.get_by_role('button', name='Start a new round').click(); await A.wait_for_timeout(300)
        await A.get_by_role('button', name='+ Friend').click(); await A.wait_for_timeout(300)
        check('The change is kept after reopening the app', await A.get_by_role('dialog').get_by_text('HCP 20.0 EST · guest').count() == 1)
        await A.get_by_role('dialog').get_by_role('button', name='Close').first.click(); await A.wait_for_timeout(200)
        await A.get_by_role('button', name='Back').first.click(); await A.wait_for_timeout(300)
        # A friend without the app, from the Friends tab
        await A.get_by_role('button', name='Friends', exact=True).click(); await A.wait_for_timeout(500)
        await A.get_by_role('button', name='Add', exact=True).click(); await A.wait_for_timeout(300)
        await A.get_by_role('button', name="Add a player who doesn't use the app").click(); await A.wait_for_timeout(200)
        await A.get_by_label('Name', exact=True).fill('Gus'); await A.get_by_label('Last name').fill('Lee')
        await A.get_by_label('Handicap index').fill('24.0'); await A.get_by_role('button', name='Add player').click(); await A.wait_for_timeout(400)
        await A.get_by_role('button', name='View Gus').click(); await A.wait_for_timeout(300)
        pe = A.get_by_role('button', name="Edit Gus's handicap")
        check("A friend without the app has Edit on their profile", await pe.count() == 1)
        await pe.click(); await A.wait_for_timeout(300)
        s2 = A.get_by_role('dialog', name="Gus's handicap")
        await s2.get_by_label('Handicap index').fill('21.5'); await s2.get_by_role('button', name='Save handicap').click(); await A.wait_for_timeout(300)
        check('Saving goes back to their profile, updated', await A.get_by_role('dialog', name='Gus Lee').get_by_text('HCP 21.5', exact=True).count() == 1)
        await A.screenshot(path=f'{OUT}/edit_hcp_profile.png')
        print('page errors:', A.errs); print(f'{sum(res)}/{len(res)} passed'); await b.close()
asyncio.run(main())
